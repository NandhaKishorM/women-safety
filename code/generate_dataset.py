"""
Build the 1000 row physics simulated MPU6050 dataset for the women safety chip.

Each row is a 2 second window sampled at 50 Hz, generated by `physics_sim.py`.
We save four artifacts inside ./dataset:
    imu_actions_1000.csv     : 14 summary features per window plus label
    imu_actions_1000.jsonl   : same data formatted as instruction tuning
                               messages for SmolLM2-135M Instruct SFT
    waveforms.npz            : raw 6 axis windows for plotting and inspection
    labels.json              : per class metadata and trigger flag

The trigger column is 1 for the repeated_kick class and 0 otherwise. The
firmware level trigger engine (see trigger.py) also fires when consecutive
windows are labelled hard_kick, but at the dataset level only repeated_kick
is the explicit trigger event.
"""

import csv
import json
import math
from pathlib import Path

import numpy as np

from physics_sim import LABELS, TRIGGER_LABELS, simulate, FS, N

OUT_DIR = Path(__file__).parent / "dataset"
OUT_DIR.mkdir(parents=True, exist_ok=True)

ROWS_PER_CLASS = 100
SEED = 7


def stats(arr):
    return float(np.mean(arr)), float(np.std(arr)), float(np.max(arr)), float(np.min(arr))


def features_from_window(acc, gyro):
    """14 dimensional summary used by the SLM prompt."""
    mag = np.sqrt(np.sum(acc ** 2, axis=1))
    jerk = np.abs(np.diff(mag)) * FS
    gmag = np.sqrt(np.sum(gyro ** 2, axis=1))
    return {
        "acc_mean_g": round(float(np.mean(mag)), 3),
        "acc_std_g": round(float(np.std(mag)), 3),
        "acc_peak_g": round(float(np.max(mag)), 3),
        "acc_min_g": round(float(np.min(mag)), 3),
        "jerk_peak": round(float(np.max(jerk)), 2),
        "jerk_mean": round(float(np.mean(jerk)), 2),
        "gyro_peak_dps": round(float(np.max(gmag)), 1),
        "gyro_std_dps": round(float(np.std(gmag)), 1),
        "ax_std": round(float(np.std(acc[:, 0])), 3),
        "ay_std": round(float(np.std(acc[:, 1])), 3),
        "az_std": round(float(np.std(acc[:, 2])), 3),
        "gx_std": round(float(np.std(gyro[:, 0])), 1),
        "gy_std": round(float(np.std(gyro[:, 1])), 1),
        "gz_std": round(float(np.std(gyro[:, 2])), 1),
    }


PROMPT = (
    "You are an on chip safety monitor for a shoe mounted MPU6050. "
    "Given the IMU window features below classify the leg action into one of: "
    "{labels}. Reply with the label only.\n"
    "{feat_line}"
)


def build_prompt(feats):
    feat_line = " ".join(f"{k}={v}" for k, v in feats.items())
    return PROMPT.format(labels=", ".join(LABELS), feat_line=feat_line)


def main():
    rng = np.random.default_rng(SEED)
    rows = []
    waveforms = {"acc": [], "gyro": [], "label": []}
    for cls in LABELS:
        for _ in range(ROWS_PER_CLASS):
            acc, gyro = simulate(cls, rng)
            f = features_from_window(acc, gyro)
            row = dict(f)
            row["label"] = cls
            row["trigger"] = 1 if cls in TRIGGER_LABELS else 0
            rows.append(row)
            waveforms["acc"].append(acc)
            waveforms["gyro"].append(gyro)
            waveforms["label"].append(cls)

    rng.shuffle(rows)

    csv_path = OUT_DIR / "imu_actions_1000.csv"
    jsonl_path = OUT_DIR / "imu_actions_1000.jsonl"
    npz_path = OUT_DIR / "waveforms.npz"
    meta_path = OUT_DIR / "labels.json"

    with open(csv_path, "w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    with open(jsonl_path, "w", encoding="utf-8") as fh:
        for r in rows:
            f = {k: r[k] for k in r if k not in ("label", "trigger")}
            sample = {
                "messages": [
                    {"role": "user", "content": build_prompt(f)},
                    {"role": "assistant", "content": r["label"]},
                ],
                "label": r["label"],
                "trigger": r["trigger"],
            }
            fh.write(json.dumps(sample) + "\n")

    np.savez_compressed(
        npz_path,
        acc=np.array(waveforms["acc"], dtype=np.float32),
        gyro=np.array(waveforms["gyro"], dtype=np.float32),
        label=np.array(waveforms["label"]),
    )

    meta = {
        "fs_hz": FS,
        "samples_per_window": N,
        "n_classes": len(LABELS),
        "labels": LABELS,
        "trigger_labels": list(TRIGGER_LABELS),
        "rows_per_class": ROWS_PER_CLASS,
        "total_rows": len(rows),
        "feature_names": list(features_from_window(np.zeros((N, 3)), np.zeros((N, 3))).keys()),
    }
    meta_path.write_text(json.dumps(meta, indent=2))

    print(f"wrote {len(rows)} rows")
    print(f"  csv:        {csv_path}")
    print(f"  jsonl:      {jsonl_path}")
    print(f"  waveforms:  {npz_path}")
    print(f"  meta:       {meta_path}")


if __name__ == "__main__":
    main()
